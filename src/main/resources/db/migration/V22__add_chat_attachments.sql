CREATE TABLE IF NOT EXISTS chat_attachment (
  id VARCHAR(36) NOT NULL PRIMARY KEY,
  user_id BIGINT NOT NULL,
  conversation_id BIGINT NULL,
  message_id BIGINT NULL,
  kind VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  content_type VARCHAR(128) NOT NULL,
  file_size BIGINT NOT NULL,
  storage_provider VARCHAR(32) NOT NULL,
  storage_path VARCHAR(1024) NOT NULL,
  bucket VARCHAR(128) NULL,
  object_key VARCHAR(512) NOT NULL,
  width INT NULL,
  height INT NULL,
  position INT NULL,
  created_at DATETIME NOT NULL,
  attached_at DATETIME NULL,
  expires_at DATETIME NULL,
  UNIQUE KEY uk_chat_attachment_object_key (object_key),
  KEY idx_chat_attachment_user_id (user_id, id),
  KEY idx_chat_attachment_message_position (message_id, position),
  KEY idx_chat_attachment_status_expiry (status, expires_at)
);
