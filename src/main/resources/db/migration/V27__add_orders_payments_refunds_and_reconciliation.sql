CREATE TABLE billing_order (
  id BIGINT NOT NULL PRIMARY KEY,
  order_no VARCHAR(64) NOT NULL,
  user_id BIGINT NOT NULL,
  account_id BIGINT NOT NULL,
  order_type VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL,
  product_code VARCHAR(64) NOT NULL,
  price_version_code VARCHAR(64) NOT NULL,
  product_snapshot JSON NOT NULL,
  currency CHAR(3) NOT NULL,
  original_amount_minor BIGINT NOT NULL,
  discount_amount_minor BIGINT NOT NULL DEFAULT 0,
  payable_amount_minor BIGINT NOT NULL,
  paid_amount_minor BIGINT NOT NULL DEFAULT 0,
  client_request_id VARCHAR(128) NOT NULL,
  expires_at DATETIME(6) NOT NULL,
  paid_at DATETIME(6) NULL,
  fulfilled_at DATETIME(6) NULL,
  closed_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  UNIQUE KEY uk_billing_order_no (order_no),
  UNIQUE KEY uk_billing_order_user_request (user_id, client_request_id),
  KEY idx_billing_order_user_time (user_id, created_at),
  KEY idx_billing_order_status_expiry (status, expires_at),
  CONSTRAINT fk_billing_order_account FOREIGN KEY (account_id) REFERENCES commercial_account(id)
);
CREATE TABLE payment_attempt (
  id BIGINT NOT NULL PRIMARY KEY,
  payment_no VARCHAR(64) NOT NULL,
  order_id BIGINT NOT NULL,
  provider VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL,
  currency CHAR(3) NOT NULL,
  amount_minor BIGINT NOT NULL,
  provider_transaction_id VARCHAR(128) NULL,
  checkout_payload_encrypted TEXT NULL,
  expires_at DATETIME(6) NOT NULL,
  succeeded_at DATETIME(6) NULL,
  closed_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  UNIQUE KEY uk_payment_attempt_no (payment_no),
  UNIQUE KEY uk_payment_provider_transaction (provider, provider_transaction_id),
  KEY idx_payment_order_status (order_id, status),
  CONSTRAINT fk_payment_attempt_order FOREIGN KEY (order_id) REFERENCES billing_order(id)
);

CREATE TABLE payment_webhook_event (
  id BIGINT NOT NULL PRIMARY KEY,
  provider VARCHAR(32) NOT NULL,
  provider_event_id VARCHAR(128) NOT NULL,
  payload_hash CHAR(64) NOT NULL,
  signature_valid BOOLEAN NOT NULL,
  process_status VARCHAR(32) NOT NULL,
  payment_no VARCHAR(64) NULL,
  received_at DATETIME(6) NOT NULL,
  processed_at DATETIME(6) NULL,
  error_code VARCHAR(64) NULL,
  UNIQUE KEY uk_payment_webhook_event (provider, provider_event_id)
);

CREATE TABLE refund_order (
  id BIGINT NOT NULL PRIMARY KEY,
  refund_no VARCHAR(64) NOT NULL,
  request_id VARCHAR(128) NOT NULL,
  order_id BIGINT NOT NULL,
  payment_attempt_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  status VARCHAR(32) NOT NULL,
  currency CHAR(3) NOT NULL,
  amount_minor BIGINT NOT NULL,
  reason_code VARCHAR(64) NOT NULL,
  reason_note VARCHAR(512) NULL,
  provider_refund_id VARCHAR(128) NULL,
  requested_by BIGINT NOT NULL,
  succeeded_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  UNIQUE KEY uk_refund_no (refund_no),
  UNIQUE KEY uk_refund_order_request (order_id, request_id),
  KEY idx_refund_user_time (user_id, created_at),
  CONSTRAINT fk_refund_order_order FOREIGN KEY (order_id) REFERENCES billing_order(id),
  CONSTRAINT fk_refund_payment_attempt FOREIGN KEY (payment_attempt_id) REFERENCES payment_attempt(id)
);

CREATE TABLE billing_outbox (
  id BIGINT NOT NULL PRIMARY KEY,
  aggregate_type VARCHAR(32) NOT NULL,
  aggregate_id VARCHAR(128) NOT NULL,
  event_type VARCHAR(32) NOT NULL,
  event_version INT NOT NULL,
  payload_json JSON NULL,
  status VARCHAR(32) NOT NULL,
  retry_count INT NOT NULL DEFAULT 0,
  next_attempt_at DATETIME(6) NOT NULL,
  last_error VARCHAR(512) NULL,
  created_at DATETIME(6) NOT NULL,
  processed_at DATETIME(6) NULL,
  UNIQUE KEY uk_billing_outbox_event (aggregate_type, aggregate_id, event_type, event_version),
  KEY idx_billing_outbox_ready (status, next_attempt_at)
);

CREATE TABLE payment_reconciliation_item (
  id BIGINT NOT NULL PRIMARY KEY,
  reconciliation_date DATE NOT NULL,
  provider VARCHAR(32) NOT NULL,
  payment_no VARCHAR(64) NULL,
  provider_transaction_id VARCHAR(128) NULL,
  internal_amount_minor BIGINT NULL,
  provider_amount_minor BIGINT NULL,
  internal_status VARCHAR(32) NULL,
  provider_status VARCHAR(32) NULL,
  difference_type VARCHAR(32) NOT NULL,
  process_status VARCHAR(32) NOT NULL,
  assignee_user_id BIGINT NULL,
  note VARCHAR(512) NULL,
  resolved_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  UNIQUE KEY uk_reconciliation_item (
    reconciliation_date,
    provider,
    payment_no,
    provider_transaction_id,
    difference_type
  ),
  KEY idx_reconciliation_status_date (process_status, reconciliation_date)
);
